/**
 * ----------------------------------------------------------------------
 * Function given to help user to continue LwIP Initialization
 * Up to user to complete or change this function ...
 * Up to user to call this function in main.c in while (1) of main(void)
 *-----------------------------------------------------------------------
 * Read a received packet from the Ethernet buffers
 * Send it to the lwIP stack for handling
 * Handle timeouts if LWIP_TIMERS is set and without RTOS
 * Handle the llink status if LWIP_NETIF_LINK_CALLBACK is set and without RTOS
 */
void MX_LWIP_Process(void)
{
/* USER CODE BEGIN 4_1 */
  /* DHCP 定时器驱动（裸机模式下 dhcp_*_tmr 不挂 sys_timeout，必须由主循环手动调用）：
     fine 每 500ms 处理请求超时/重传，coarse 每 60s 处理租约续租/重绑 */
  static uint32_t dhcp_fine_tick   = 0;
  static uint32_t dhcp_coarse_tick = 0;
  uint32_t now = HAL_GetTick();
  if ((uint32_t)(now - dhcp_fine_tick) >= DHCP_FINE_TIMER_MSECS)
  {
    dhcp_fine_tick = now;
    dhcp_fine_tmr();
  }
  if ((uint32_t)(now - dhcp_coarse_tick) >= DHCP_COARSE_TIMER_MSECS)
  {
    dhcp_coarse_tick = now;
    dhcp_coarse_tmr();
  }
/* USER CODE END 4_1 */
  /* 中断驱动：仅在 ETH 中断标志置位时才读取帧（原为无条件轮询 ethernetif_input） */
  if (g_eth_rx_flag)
  {
    g_eth_rx_flag = 0;
    ethernetif_input(&gnetif);
  }

/* USER CODE BEGIN 4_2 */
/* USER CODE END 4_2 */
  /* Handle timeouts */
  sys_check_timeouts();

  Ethernet_Link_Periodic_Handle(&gnetif);

/* USER CODE BEGIN 4_3 */
/* USER CODE END 4_3 */
}

/**
  * @brief  Notify the User about the network interface config status
  * @param  netif: the network interface
  * @retval None
  */
static void ethernet_link_status_updated(struct netif *netif)
{
  if (netif_is_up(netif))
  {
/* USER CODE BEGIN 5 */
    dhcp_start(netif);   /* 链路恢复：重新发起 DHCP */
/* USER CODE END 5 */
  }
  else /* netif is down */
  {
/* USER CODE BEGIN 6 */
    dhcp_stop(netif);    /* 链路断开：停止 DHCP */
/* USER CODE END 6 */
  }
}

